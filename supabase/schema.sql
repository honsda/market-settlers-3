-- Settlers Market — Supabase schema
--
-- Run this in the Supabase SQL editor, or apply it with:
--   SUPABASE_ACCESS_TOKEN=sbp_... npm run db:push-schema
--
-- The application talks to Postgres through the secret API key on the server.
-- RLS is enabled with no public policies: the publishable key cannot read or
-- write these tables. The service role bypasses RLS by design.
--
-- Timestamps are Unix milliseconds (bigint), matching the app's Offer model.

-- ── Offers ──────────────────────────────────────────────────────────────────
create table if not exists public.offers (
	id text primary key,
	side text not null check (side in ('buy', 'sell')),
	item_id text not null,
	quantity integer not null check (quantity > 0),
	price double precision not null check (price > 0),
	ign text not null,
	guild text not null default '',
	contact text not null default '',
	world text not null default 'Caeldun',
	x integer,
	y integer,
	z integer,
	note text not null default '',
	status text not null default 'open' check (status in ('open', 'filled', 'cancelled')),
	source text not null default 'web' check (source in ('web', 'discord', 'seed')),
	edit_token text not null,
	created_at bigint not null,
	updated_at bigint not null
);

create index if not exists idx_offers_open on public.offers (status, item_id, side);
create index if not exists idx_offers_created on public.offers (created_at desc);
create index if not exists idx_offers_ign on public.offers (lower(ign));
create index if not exists idx_offers_guild on public.offers (lower(guild)) where guild <> '';

-- ── Price history ───────────────────────────────────────────────────────────
create table if not exists public.price_history (
	id bigint generated by default as identity primary key,
	item_id text not null,
	bid double precision,
	ask double precision,
	ts bigint not null
);

create index if not exists idx_history_item_ts on public.price_history (item_id, ts);
create index if not exists idx_history_ts on public.price_history (ts);

-- ── Alert queue ─────────────────────────────────────────────────────────────
create table if not exists public.alerts (
	id text primary key,
	item_id text not null,
	kind text not null check (kind in ('price-up', 'price-down', 'new-high', 'new-low')),
	side text not null check (side in ('buy', 'sell')),
	price double precision not null,
	previous double precision,
	change_pct double precision,
	message text not null,
	created_at bigint not null,
	posted_at bigint,
	discord_message_id text
);

create index if not exists idx_alerts_created on public.alerts (created_at desc);
create index if not exists idx_alerts_pending on public.alerts (created_at)
	where posted_at is null;

-- ── Metadata / revision counter ─────────────────────────────────────────────
create table if not exists public.meta (
	key text primary key,
	value text not null
);

insert into public.meta (key, value)
values ('revision', '1')
on conflict (key) do nothing;

-- Atomic revision bump used by the web app and the bot. The SSE endpoint polls
-- this counter; writes from either process become visible to the dashboard.
create or replace function public.bump_revision()
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
	next_value bigint;
begin
	update public.meta
	   set value = ((value::bigint) + 1)::text
	 where key = 'revision'
	returning value::bigint into next_value;

	if next_value is null then
		insert into public.meta (key, value)
		values ('revision', '2')
		on conflict (key) do update
			set value = ((public.meta.value::bigint) + 1)::text
		returning value::bigint into next_value;
	end if;

	return next_value;
end;
$$;

revoke all on function public.bump_revision() from public;
grant execute on function public.bump_revision() to service_role;

-- ── Access control ──────────────────────────────────────────────────────────
alter table public.offers enable row level security;
alter table public.price_history enable row level security;
alter table public.alerts enable row level security;
alter table public.meta enable row level security;

revoke all on public.offers from anon, authenticated;
revoke all on public.price_history from anon, authenticated;
revoke all on public.alerts from anon, authenticated;
revoke all on public.meta from anon, authenticated;

grant select, insert, update, delete on public.offers to service_role;
grant select, insert, update, delete on public.price_history to service_role;
grant select, insert, update, delete on public.alerts to service_role;
grant select, insert, update, delete on public.meta to service_role;
grant usage, select on sequence public.price_history_id_seq to service_role;

-- ── Convenience view for the dashboard (optional) ───────────────────────────
create or replace view public.open_offers as
select *
from public.offers
where status = 'open';

revoke all on public.open_offers from anon, authenticated;
grant select on public.open_offers to service_role;
